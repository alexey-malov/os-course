
#!/usr/bin/env python3
"""Проверка формата CSV-отчётов и согласованности статистики симуляции.

Скрипт принимает два файла:
1. summary.csv — сводная статистика всего эксперимента.
2. events.csv — подробная информация о каждом запланированном задании.

Проверяется, что показатели в отчётах не противоречат друг другу.
Используется только стандартная библиотека Python.

Важно: не запускайте тест с флагом -O, поскольку он отключает assert.
"""

import csv
import math
import sys
from pathlib import Path


# Проверяем количество аргументов командной строки.
# Пользователь должен передать пути к двум CSV-файлам.
if len(sys.argv) != 3:
    raise SystemExit('usage: validate_output.py <summary.csv> <events.csv>')

summary_file, events_file = map(Path, sys.argv[1:])


# ============================================================
# 1. Проверка сводного отчёта summary.csv
# ============================================================

# DictReader читает CSV как последовательность словарей.
# Ключи словаря — названия столбцов из первой строки файла.
with summary_file.open(newline='', encoding='utf-8') as f:
    rows = list(csv.DictReader(f))

# Один запуск симуляции должен создавать ровно одну строку
# сводной статистики.
assert len(rows) == 1, 'Exactly one summary row is expected'

r = rows[0]

# Интегральная оценка качества игры должна находиться
# в диапазоне от 0 до 100 баллов.
assert 0 <= float(r['game_score']) <= 100

# Проверяем, что измеренная продолжительность эксперимента
# составляет не менее одной секунды.
assert float(r['duration_s']) >= 1


# Проверяем статистику трёх периодических задач:
# Audio, Frame и AI.
for role in ('audio', 'frame', 'ai'):

    # planned   — сколько заданий должно было быть запущено
    #             согласно периодическому расписанию.
    # completed — сколько заданий действительно завершилось.
    # skipped   — сколько запланированных заданий было пропущено.
    # late      — сколько завершённых заданий нарушило дедлайн.
    planned = int(r[f'{role}_planned'])
    completed = int(r[f'{role}_completed'])
    skipped = int(r[f'{role}_skipped'])
    late = int(r[f'{role}_late'])

    # Каждое запланированное задание должно быть учтено:
    # оно либо завершилось, либо было пропущено.
    #
    # Это позволяет обнаружить потерянные или дважды
    # учтённые задания в статистике симуляции.
    assert planned == completed + skipped, (role, 'job accounting')

    # Число завершённых с опозданием заданий не может
    # быть отрицательным или превышать число завершённых.
    #
    # Пропущенные задания здесь не учитываются:
    # они хранятся отдельно в skipped.
    assert 0 <= late <= completed, (role, 'late count')

    # Нарушением временных требований считается:
    # 1. Задание, завершённое после дедлайна (late).
    # 2. Задание, которое вообще не было выполнено (skipped).
    #
    # Вычисляем ожидаемый процент таких заданий.
    expected_percent = 100 * (late + skipped) / planned

    # Проверяем, что процент нарушений в сводном отчёте
    # соответствует значениям счётчиков.
    #
    # math.isclose используется вместо точного сравнения,
    # поскольку при записи дробных чисел в CSV возможны
    # небольшие погрешности округления.
    assert math.isclose(
        expected_percent,
        float(r[f'{role}_miss_pct']),
        abs_tol=1e-4
    )

    # Оценка качества отдельной периодической задачи
    # должна находиться в диапазоне от 0 до 100.
    assert 0 <= float(r[f'{role}_q']) <= 100

    # P99 времени отклика не может быть отрицательным.
    # Эта проверка не оценивает соблюдение дедлайна,
    # а только корректность записанного значения.
    assert float(r[f'{role}_p99_response_ms']) >= 0


# ============================================================
# 2. Проверка подробного отчёта events.csv
# ============================================================

# Читаем записи об отдельных заданиях.
# Каждая строка описывает один запланированный экземпляр
# периодической задачи Audio, Frame или AI.
with events_file.open(newline='', encoding='utf-8') as f:
    event_rows = list(csv.DictReader(f))

# Общее количество строк в events.csv должно совпадать
# с суммарным количеством запланированных заданий
# всех трёх периодических потоков.
#
# Это проверяет, что подробный отчёт содержит запись
# для каждого запланированного задания.
assert len(event_rows) == sum(
    int(r[f'{role}_planned'])
    for role in ('audio', 'frame', 'ai')
)


# Проверяем подробные записи отдельно для каждой роли.
#
# В summary.csv используются имена audio, frame, ai,
# а в events.csv — Audio, Frame, AI.
for role, name in [
    ('audio', 'Audio'),
    ('frame', 'Frame'),
    ('ai', 'AI')
]:

    # Выбираем из подробного отчёта только события
    # текущего типа задачи.
    matched = [e for e in event_rows if e['role'] == name]

    # Число записей о заданиях конкретной роли должно
    # совпадать со значением planned в сводном отчёте.
    assert len(matched) == int(r[f'{role}_planned'])

    for e in matched:

        # Поле missed показывает нарушение дедлайна.
        # Поле skipped показывает, что задание было пропущено.
        #
        # Оба поля должны содержать только 0 или 1.
        assert e['missed'] in {'0', '1'}
        assert e['skipped'] in {'0', '1'}

        if e['skipped'] == '1':

            # Пропущенное задание не выполнялось,
            # поэтому у него не может быть времени завершения.
            assert e['finish_ms'] == ''

            # Любое пропущенное задание автоматически
            # считается нарушившим временные требования.
            assert e['missed'] == '1'

        else:

            # Если задание не пропущено, оно должно
            # иметь зафиксированное время завершения.
            assert e['finish_ms'] != ''

            # Время отклика отсчитывается от запланированного
            # момента запуска до завершения задания.
            # Оно не может быть отрицательным.
            assert float(e['response_ms']) >= 0


# Все проверки завершились без нарушения инвариантов.
# Если хотя бы один assert не выполнится,
# Python остановит скрипт с ошибкой AssertionError.
print('CSV invariants: PASS')
